import { useState } from "react";
import { Bot, Loader2, RefreshCw, Sparkles } from "lucide-react";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { aiApi } from "@/services";
import type { AICoachResponse } from "@/types/api";

export function AICoachCard() {
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<AICoachResponse | null>(null);

  const generate = async () => {
    setLoading(true);
    try {
      const res = await aiApi.coach();
      if (res.available && res.insights.length === 0) {
        toast.info("Complete a focus session first — the coach needs some data to work with.");
      }
      setResult(res);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "AI coach request failed");
    } finally {
      setLoading(false);
    }
  };

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-base">
          <Bot className="size-4 text-primary" /> AI coach
        </CardTitle>
        <CardDescription>Groq-powered insights generated from your analytics</CardDescription>
      </CardHeader>
      <CardContent>
        {result?.available === false ? (
          <p className="text-sm text-muted-foreground">
            AI coach is not configured. Set <code className="rounded bg-muted px-1 py-0.5 text-xs">GROQ_API_KEY</code>{" "}
            in <code className="rounded bg-muted px-1 py-0.5 text-xs">backend/.env</code> and restart the backend.
          </p>
        ) : result?.insights.length ? (
          <ul className="space-y-3">
            {result.insights.map((ins, i) => (
              <li key={i} className="rounded-lg bg-muted/50 p-3">
                <p className="flex items-center gap-1.5 text-sm font-medium">
                  <Sparkles className="size-3.5 text-primary" /> {ins.title}
                </p>
                <p className="mt-1 text-xs leading-relaxed text-muted-foreground">{ins.text}</p>
              </li>
            ))}
            {result.model && (
              <li className="pt-1 text-[11px] text-muted-foreground/70 list-none">Generated by {result.model}</li>
            )}
          </ul>
        ) : !loading ? (
          <p className="text-sm text-muted-foreground">
            Get personalised coaching based on your Pomodoros, streaks, distractions and task completion.
          </p>
        ) : null}

        <Button onClick={generate} disabled={loading} variant={result?.insights.length ? "outline" : "default"} className="mt-4 w-full" size="sm">
          {loading ? <Loader2 className="size-4 animate-spin" /> : result?.insights.length ? <RefreshCw className="size-4" /> : <Sparkles className="size-4" />}
          {loading ? "Thinking…" : result?.insights.length ? "Regenerate" : "Generate insights"}
        </Button>
      </CardContent>
    </Card>
  );
}
